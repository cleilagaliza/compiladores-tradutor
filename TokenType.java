public enum TokenType {
    PLUS,       // +
    MINUS,      // -
    STAR,       // *
    SLASH,      // /
    NUMBER,     // Números de múltiplos dígitos
    IDENT,      // Identificadores (nomes de variáveis)
    LET,        // Palavra reservada 'let'
    PRINT,      // Palavra reservada 'print'
    EQ,         // =
    SEMICOLON,  // ;
    EOF         // Fim de arquivo
}
